"""Bundle public Markdown and showcase metadata for the dependency-free docs site."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
from typing import Any


ROOT = Path(__file__).resolve().parents[1]
PUBLIC_FOLDERS = ("getting-started", "guides", "api")
SECTIONS = {"getting-started": "Getting started", "guides": "Guides", "api": "API reference"}
PAGE_ORDER = {
    "readme": 0, "getting-started/installation": 10, "getting-started/quickstart": 11,
    "guides/characters": 20, "guides/endgame": 21, "guides/player-cards": 22,
    "guides/builds": 23, "guides/caching": 24, "guides/github-pages": 25,
    "api/main-client": 30,
    "api/nanoka-client": 31, "api/prydwen-client": 32, "api/hoyolab-client": 33,
    "api/card-functions": 34, "api/provider-apis": 35, "api/results": 36,
    "api/cache": 37, "api/errors": 38,
    "api/nanoka/characters": 40, "api/nanoka/equipment": 41,
    "api/nanoka/monsters": 42, "api/nanoka/schedules": 43,
    "api/nanoka/items-currency": 44, "api/nanoka/assets": 45,
    "api/nanoka-models": 50, "api/hoyolab-models": 51,
    "api/prydwen-models": 52, "showcase": 100,
}


def project_version(root: Path) -> str:
    """Read the published project version without importing the runtime library."""
    source = (root / "pyproject.toml").read_text(encoding="utf-8")
    project = re.search(r"(?ms)^\[project\]\s*(.*?)(?=^\[|\Z)", source)
    match = re.search(r'^version\s*=\s*[\"\']([^\"\']+)[\"\']', project.group(1), re.M) if project else None
    if match is None:
        raise ValueError("pyproject.toml has no [project] version")
    return match.group(1)


def markdown_files(docs: Path) -> list[Path]:
    """Find the public documentation sources, excluding internal migration plans."""
    paths = [path for path in docs.glob("*.md") if path.name.lower() in {"readme.md", "showcase.md"}]
    for folder in PUBLIC_FOLDERS:
        paths.extend((docs / folder).rglob("*.md"))
    return sorted(paths, key=lambda path: (PAGE_ORDER.get(path.relative_to(docs).with_suffix("").as_posix().lower(), 50), path.as_posix()))


def page_title(markdown: str, fallback: str) -> str:
    """Return the first level-one title, falling back to a readable filename."""
    match = re.search(r"^#\s+(.+?)\s*#*\s*$", markdown, re.M)
    return match.group(1).replace("`", "").strip() if match else fallback.replace("-", " ").capitalize()


def load_docs(root: Path = ROOT) -> dict[str, Any]:
    """Load a deterministic public-page catalog and optional showcase metadata.

    Page IDs are POSIX paths relative to docs/, without the Markdown extension.
    Original Markdown remains the source of truth. Missing showcase metadata is
    allowed while authoring; validation checks the complete publishable site.
    """
    docs = root / "docs"
    pages = []
    for path in markdown_files(docs):
        identifier = path.relative_to(docs).with_suffix("").as_posix()
        if identifier.lower() in {"readme", "showcase"}:
            identifier = identifier.lower()
        content = path.read_text(encoding="utf-8-sig")
        section = SECTIONS.get(identifier.split("/")[0], "Showcase" if identifier == "showcase" else "Overview")
        pages.append({"id": identifier, "title": page_title(content, path.stem), "section": section, "content": content})
    showcase_path = docs / "data" / "showcase.json"
    showcase = json.loads(showcase_path.read_text(encoding="utf-8")) if showcase_path.is_file() else {"items": [], "unavailable": []}
    return {"version": project_version(root), "pages": pages, "showcase": showcase}


def render_bundle(catalog: dict[str, Any]) -> str:
    """Serialize external-script-safe JSON for HTTP, subpath, and file:// loading."""
    payload = json.dumps(catalog, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    payload = payload.replace("<", "\\u003c").replace(">", "\\u003e").replace("&", "\\u0026")
    payload = payload.replace("\u2028", "\\u2028").replace("\u2029", "\\u2029")
    return "// Generated by scripts/build_docs.py; edit the Markdown sources instead.\nwindow.HSR_DOCS = " + payload + ";\n"


def build(root: Path = ROOT, *, check: bool = False) -> Path:
    """Write content.js, or raise ValueError when --check finds a stale bundle."""
    destination = root / "docs" / "data" / "content.js"
    expected = render_bundle(load_docs(root)).encode("utf-8")
    if check:
        if not destination.is_file() or destination.read_bytes() != expected:
            raise ValueError("Docs bundle is stale. Run: python scripts/build_docs.py")
    else:
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(expected)
    return destination


def main() -> None:
    """Build the public site catalog; --check validates it without modifying files."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when the checked-in bundle differs from Markdown/metadata")
    args = parser.parse_args()
    try:
        destination = build(check=args.check)
    except (OSError, ValueError) as error:
        parser.exit(1, f"{error}\n")
    print(f"Docs bundle {'verified' if args.check else 'built'}: {destination.relative_to(ROOT).as_posix()}")


if __name__ == "__main__":
    main()
